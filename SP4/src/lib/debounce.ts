/**
 * times — мітки часу натискань (мс від початку набору), ms — пауза, після
 * якої запит таки іде. Кожен сплеск натискань закінчується одним запитом:
 * через ms після останнього натискання сплеску. Сусідні натискання, між
 * якими менше ніж ms, належать одному сплеску — тобто попередній таймер
 * скасовано, і його мить у відповідь не потрапляє.
 */
export function shouldFireAt(times: number[], ms: number): number[] {
  const fires: number[] = []
  for (let i = 0; i < times.length; i++) {
    const next = times[i + 1]
    if (next === undefined || next - times[i] >= ms) {
      fires.push(times[i] + ms)
    }
  }
  return fires
}
